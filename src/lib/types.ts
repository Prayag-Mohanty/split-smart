/**
 * Domain model shared by the pure logic modules (src/lib) and the UI.
 * Every monetary field is an integer number of paise.
 */
import type { Paise } from './money';

export type MemberId = string;

export interface Member {
  id: MemberId;
  name: string;
  /** Hex colour used for the avatar. */
  color: string;
  /** Optional emoji avatar shown instead of initials. */
  emoji?: string;
  /** Optional UPI ID (VPA) so others can pay this member via UPI deep links. */
  upiId?: string;
}

export const CATEGORIES = ['Food', 'Groceries', 'Travel', 'Utilities', 'Entertainment', 'Other'] as const;
export type Category = (typeof CATEGORIES)[number];

export type SplitMode = 'equal' | 'exact' | 'percent' | 'shares';

/**
 * How a manual expense is divided.
 *  - equal:   `values` ignored
 *  - exact:   `values[id]` is that member's amount in paise
 *  - percent: `values[id]` is a percentage (may have decimals, must total 100)
 *  - shares:  `values[id]` is a share weight, e.g. 2 : 1 : 1
 */
export interface SplitSpec {
  mode: SplitMode;
  participants: MemberId[];
  values: Record<MemberId, number>;
}

/** A single parsed/edited line on a receipt. */
export interface ReceiptItem {
  id: string;
  name: string;
  qty: number;
  unitPaise: Paise;
  totalPaise: Paise;
  category: Category;
  /** Was the category set by a human (true) or the model / default (false)? */
  categoryLocked?: boolean;
  assignees: MemberId[];
}

export type AdjustmentKind = 'tax' | 'service' | 'discount' | 'other';

/**
 * A bill-level charge (tax, service charge, packing...) or reduction (discount, round-off).
 * `amountPaise` is the signed effect on the bill: discounts are stored as negative numbers.
 */
export interface Adjustment {
  id: string;
  label: string;
  kind: AdjustmentKind;
  amountPaise: Paise;
}

interface ExpenseBase {
  id: string;
  description: string;
  /** ISO date (yyyy-mm-dd). */
  date: string;
  payerId: MemberId;
  category: Category;
  createdAt: number;
  /** Set when this expense was generated by a recurring template. */
  recurringId?: string;
}

export interface ManualExpense extends ExpenseBase {
  kind: 'manual';
  totalPaise: Paise;
  split: SplitSpec;
}

export interface ItemizedExpense extends ExpenseBase {
  kind: 'itemized';
  items: ReceiptItem[];
  adjustments: Adjustment[];
  /** Total printed on the receipt, if one was detected / confirmed. */
  printedTotalPaise?: Paise;
}

export type Expense = ManualExpense | ItemizedExpense;

/** A payment recorded between two members, e.g. after following a suggested settlement. */
export interface Settlement {
  id: string;
  fromId: MemberId;
  toId: MemberId;
  amountPaise: Paise;
  date: string;
  note?: string;
}

export type RecurrenceFrequency = 'weekly' | 'monthly';

/** Template that automatically creates a manual expense every cycle (e.g. Wi-Fi recharge). */
export interface RecurringExpense {
  id: string;
  description: string;
  totalPaise: Paise;
  payerId: MemberId;
  category: Category;
  split: SplitSpec;
  frequency: RecurrenceFrequency;
  /** ISO date of the next occurrence that has not been created yet. */
  nextDate: string;
  active: boolean;
}

export interface Group {
  id: string;
  name: string;
  emoji?: string;
  createdAt: number;
  members: Member[];
  expenses: Expense[];
  settlements: Settlement[];
  recurring: RecurringExpense[];
  /** Which member is the person using this device ("You"). Unset for imported groups until chosen. */
  meId?: MemberId;
  /**
   * Combine debts into the fewest payments (default true). When false, everyone settles
   * each person-to-person debt directly, as it arose.
   */
  simplifyDebts?: boolean;
}

/** A personal (per-device) default for new expenses in a group. Never exported with the group. */
export interface DefaultSplit {
  payerId?: MemberId;
  split: SplitSpec;
}
